export function streetRegionLabel(region:string,language:Language):string{
  const locale=language==='zh'?'zh-CN':language==='pt'?'pt-BR':language;
  try{return new Intl.DisplayNames([locale,'en'],{type:'region'}).of(region)??region;}
  catch{return region;}
}
