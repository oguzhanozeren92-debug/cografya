-- Globriva / Medeniyet Dedektifi — content engine (no client writes).
-- Existing curated cases are seeded separately; future published cases can be
-- inserted in Supabase without redeploying App Store / website.
create table if not exists public.history_cases(
  id text primary key check(id ~ '^history-[a-z0-9-]{2,65}$'),
  panorama_id text,
  panorama_path text,
  monument jsonb not null,
  place jsonb not null,
  era jsonb not null,
  tradition jsonb not null,
  purpose jsonb not null,
  clue jsonb not null,
  fact jsonb not null,
  source_url text not null,
  region text not null default 'global',
  category text not null default 'heritage',
  difficulty smallint not null default 1 check(difficulty between 1 and 3),
  status text not null default 'draft' check(status in ('draft','published','archived')),
  position int not null default 500 check(position >= 0),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint history_panorama_required check(panorama_id is not null or panorama_path is not null),
  constraint history_safe_path check(panorama_path is null or panorama_path ~ '^panoramas/[a-zA-Z0-9_-]{8,80}$')
);
create table if not exists public.history_case_media(
  id bigint generated by default as identity primary key,
  case_id text not null references public.history_cases(id) on delete cascade,
  kind text not null check(kind in ('panorama','detail','map','plan')),
  sort_order int not null default 0 check(sort_order between 0 and 1000),
  file_title text,
  asset_path text,
  artist text not null,
  license text not null,
  source_url text not null,
  caption jsonb not null default '{"tr":"","en":""}'::jsonb,
  reviewed boolean not null default false,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  unique(case_id,kind,sort_order),
  constraint media_asset_reference check(file_title is not null or asset_path is not null),
  constraint media_safe_path check(asset_path is null or asset_path ~ '^panoramas/[a-zA-Z0-9_-]{8,80}$')
);
create table if not exists public.history_case_questions(
  id bigint generated by default as identity primary key,
  case_id text not null references public.history_cases(id) on delete cascade,
  sort_order int not null check(sort_order between 1 and 10),
  prompt jsonb not null,
  options jsonb not null,
  correct smallint not null check(correct between 0 and 3),
  explanation jsonb not null,
  points int not null default 0 check(points between 0 and 2000),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  unique(case_id,sort_order)
);
create index if not exists history_cases_published_order on public.history_cases(status,position);
create index if not exists history_media_live on public.history_case_media(case_id,published,sort_order);
create index if not exists history_questions_live on public.history_case_questions(case_id,published,sort_order);

alter table public.history_cases enable row level security;
alter table public.history_case_media enable row level security;
alter table public.history_case_questions enable row level security;

-- Published heritage content is public; drafting and modification remain admin-only.
create policy "read published historical cases" on public.history_cases for select
  to anon,authenticated using (status='published');
create policy "read approved media of published cases" on public.history_case_media for select
  to anon,authenticated using (
    published and reviewed and exists (
      select 1 from public.history_cases c where c.id=case_id and c.status='published'
    )
  );
create policy "read published historical questions" on public.history_case_questions for select
  to anon,authenticated using (
    published and exists (
      select 1 from public.history_cases c where c.id=case_id and c.status='published'
    )
  );

revoke all on public.history_cases,public.history_case_media,public.history_case_questions from public,anon,authenticated;
grant select on public.history_cases,public.history_case_media,public.history_case_questions to anon,authenticated;
-- Publishing uses privileged admin/database connection, never a browser key.
